import assert from 'node:assert/strict';
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { format, type FormatConfig } from 'oxfmt';
import { economyInputs } from './economy-inputs';
import { progressionRuns, restsOf, type ProgressionRun } from './progression-model';
import { progression, road, regionById, type WayLabel } from '../lib/progression';

/**
 * Plays the C33 economy sim's three resters through the progression spine and writes
 * docs/story/pacing.md. `--check` fails when the page is stale (npm run check:progression).
 */
const WEEKS = 26;
const PATH = 'docs/story/pacing.md';

const day = (n: number | undefined) => (n === undefined ? '–' : String(n));
const row = (cells: (string | number)[]) => `| ${cells.join(' | ')} |`;
const head = (cells: string[]) =>
  [row(cells), row(cells.map((_, i) => (i === 0 ? '---' : '---:')))].join('\n');

function wayCell(run: ProgressionRun, id: WayLabel) {
  const w = run.ways[id];
  return w ? `${w.day}${w.by === 'dust' ? ' (Dust)' : ''}` : '–';
}
function folkBy(run: ProgressionRun, by: number) {
  return Object.values(run.folk).filter((d) => d <= by).length;
}
function fullMoon(run: ProgressionRun) {
  const days = Object.values(run.folk).sort((a, b) => a - b);
  return days.length === 14 ? days[13] : undefined;
}
function restPerWeek(id: string) {
  const player = economyInputs.players.find((p) => p.id === id)!;
  const rests = restsOf(player, 1);
  const minutes = rests.reduce((sum, r) => sum + r.minutes, 0);
  return { rests: rests.length, hours: Math.round((minutes / 60) * 10) / 10 };
}

const label = (r: ProgressionRun) =>
  `${r.player}, ${r.policy === 'chip' ? 'chips in' : 'builds home'}`;

export function renderPacing(runs: ProgressionRun[]) {
  const pick = (variant: string, scenario: string, policy: string) =>
    runs.filter(
      (r) => r.road === variant && r.scenario.startsWith(scenario) && r.policy === policy,
    );
  const shown = [...pick('linked', 'G10', 'chip'), ...pick('linked', 'G10', 'home')];
  const lines: string[] = [];
  lines.push(
    '# Pacing: three resters through the progression spine',
    '',
    `Generated by \`npm run sim:progression\` from [art/story/progression.json](../../art/story/progression.json), [scripts/progression-model.ts](../../scripts/progression-model.ts) and the C33 economy sim ([scripts/economy-inputs.ts](../../scripts/economy-inputs.ts), [docs/codex/economy-sim.md](../codex/economy-sim.md)). A deterministic solo ledger over ${WEEKS} weeks from a Monday, not a measurement of anyone: the three schedules are the economy sim's explicit assumptions, and every rule is a proposal (see [progression.md](progression.md) and [choices-for-matt.md](choices-for-matt.md)). Day 1 is the first day; real minutes throughout.`,
    '',
    '## The three resters',
    '',
    head(['Rester', 'Rests a week', 'Hours of rest a week', 'In the economy sim']),
  );
  for (const p of economyInputs.players) {
    const w = restPerWeek(p.id);
    lines.push(row([p.name, w.rests, w.hours, `\`${p.id}\` (target level ${p.targetLevel})`]));
  }
  lines.push(
    '',
    "Each rester's Dream Dust is the economy sim's own day-by-day wallet after its feeding, levels and hats. On top of that, one of two Dust policies: **chips in** puts all spare Dust into the first closed way in reach (refunded if the task wins), or **builds home** spends it on the home steps instead and opens ways by tasks only. Rests go to the rest spots of the region found earliest whose story still has a chapter to give (finish what you started); any rest counts for every way in reach.",
    '',
    `## The road (story-linked, G10 earning)`,
    '',
    'The day each way opens; "(Dust)" when the Dust route won. The story links are on (a way waits for its story chapter), one way and one chapter a day at most.',
    '',
    head(['Rester', ...road.map((w) => w.id)]),
  );
  for (const r of shown) lines.push(row([label(r), ...road.map((w) => wayCell(r, w.id))]));
  lines.push(
    '',
    road.map((w) => `${w.id} ${w.name}`).join('; ') + '.',
    '',
    '## The folk (story-linked, G10)',
    '',
    'How many of the fourteen folk travel with the player by each day, and the day the moon is full (the fourteenth joins).',
    '',
    head(['Rester', 'Day 7', 'Day 14', 'Day 30', 'Day 60', 'Day 90', 'Moon full']),
  );
  for (const r of shown)
    lines.push(row([label(r), ...[7, 14, 30, 60, 90].map((d) => folkBy(r, d)), day(fullMoon(r))]));
  lines.push('', '## Each story (story-linked, G10, chipping in)', '');
  lines.push(head(['Story', ...pick('linked', 'G10', 'chip').map((r) => r.player)]));
  for (const region of progression.regions) {
    lines.push(
      row([
        `${region.id} (${progression.folk.find((f) => f.joins.kind === 'story' && f.joins.story === region.story)?.name})`,
        ...pick('linked', 'G10', 'chip').map((r) => {
          const c = r.chapters[region.id];
          return c ? c.join(', ') : '–';
        }),
      ]),
    );
  }
  lines.push(
    '',
    'Days of chapters 1, 2 and 3; the apprentice joins on the chapter 3 day.',
    '',
    '## Story links on or off',
    '',
    'The same resters with the links off (the road as #95 has it): the day Lumen opens (W9) and the day the moon is full.',
    '',
    head(['Rester', 'W9, linked', 'W9, free', 'Moon full, linked', 'Moon full, free']),
  );
  for (const r of pick('linked', 'G10', 'chip')) {
    const free = runs.find(
      (x) =>
        x.road === 'free' &&
        x.scenario === r.scenario &&
        x.policy === r.policy &&
        x.player === r.player,
    )!;
    lines.push(
      row([label(r), wayCell(r, 'W9'), wayCell(free, 'W9'), day(fullMoon(r)), day(fullMoon(free))]),
    );
  }
  lines.push(
    '',
    '## Dream Dust: G10 against L2',
    '',
    `Dust earned over ${WEEKS} weeks, and the day the road's last way opens when spare Dust is chipped in. L2 pays every real minute of a night at Rest 2x; G10 pays a night a flat 60 and tapers daytime rest past 240 a day.`,
    '',
    head(['Rester', 'Earned, G10', 'Earned, L2', 'W9 chipping in, G10', 'W9 chipping in, L2']),
  );
  for (const r of pick('linked', 'G10', 'chip')) {
    const l2 = runs.find(
      (x) =>
        x.road === 'linked' &&
        x.scenario.startsWith('L2') &&
        x.policy === 'chip' &&
        x.player === r.player,
    )!;
    lines.push(
      row([
        r.player,
        Math.round(r.dustEarned).toLocaleString('en-GB'),
        Math.round(l2.dustEarned).toLocaleString('en-GB'),
        wayCell(r, 'W9'),
        wayCell(l2, 'W9'),
      ]),
    );
  }
  lines.push(
    '',
    '## The home base (G10, building home)',
    '',
    'The day each home step finishes when spare Dust goes to the home (the Dust-only form of #146).',
    '',
    head(['Step', ...pick('linked', 'G10', 'home').map((r) => r.player)]),
  );
  for (const step of progression.home.steps)
    lines.push(
      row([
        `${step.name} (${step.dust} Dust, ${step.restMinutes} min of rest)`,
        ...pick('linked', 'G10', 'home').map((r) => day(r.home[step.id])),
      ]),
    );
  lines.push(
    '',
    '## Limits',
    '',
    '- The schedules are fixed weekly patterns; real people vary week to week, take holidays and stop and start. Nothing in the rules punishes that, so a gap only moves every date later.',
    '- The Light rester never rests 45 minutes in an evening, so without chipping in the Isles (W4), Neon (W7) and space wait for the Dust route: that is what the Dust route is for.',
    '- Regions are assumed found at the first visit after their way opens; finding spots takes a short walk the sim does not model.',
    "- Comforts, outfits and region outings are not bought or taken here; the C33 sim's level and hat purchases are.",
    `- ${regionById('lumen')?.name} is the journey's end; nothing after it is simulated.`,
    '',
  );
  return lines.join('\n');
}

async function main() {
  const root = new URL('../', import.meta.url);
  const runs = progressionRuns(['g10', 'l2'], WEEKS);
  const config: FormatConfig = JSON.parse(readFileSync(new URL('.oxfmtrc.json', root), 'utf8'));
  const page = await format(PATH, renderPacing(runs), config);
  assert.equal(page.errors.length, 0, 'the pacing page formats cleanly');
  if (process.argv.includes('--check')) {
    assert.equal(
      readFileSync(new URL(PATH, root), 'utf8'),
      page.code,
      `${PATH} is stale; run npm run sim:progression`,
    );
    console.log('Pacing page matches the spine and the economy sim.');
    return;
  }
  mkdirSync(new URL('docs/story/', root), { recursive: true });
  writeFileSync(new URL(PATH, root), page.code);
  console.log(`Wrote ${PATH}`);
}
void main().catch((error: unknown) => {
  console.error(error);
  process.exitCode = 1;
});
