import type { EconomyInputs, PlayerPolicy, Scenario, Session } from './economy-inputs';
import { total, type Simulation } from './economy-model';

const number = (value: number) => value.toLocaleString('en-GB', { maximumFractionDigits: 2 });
const time = (minute: number) =>
  `${String(Math.floor(minute / 60)).padStart(2, '0')}:${String(minute % 60).padStart(2, '0')}`;
const weekdays = ['Mon', 'Tue', 'Wed', 'Thu', 'Fri', 'Sat', 'Sun'];
const dayNames = (days: readonly number[]) => days.map((day) => weekdays[day]).join(', ');
const escapeXml = (value: string) =>
  value
    .replaceAll('&', '&amp;')
    .replaceAll('<', '&lt;')
    .replaceAll('>', '&gt;')
    .replaceAll('"', '&quot;');
const weeklyWallets = (input: EconomyInputs, result: Simulation) =>
  Array.from(
    { length: input.weeks },
    (_, week) => result.days[(week + 1) * input.daysPerWeek - 1].balance,
  );
const scenarioFor = (input: EconomyInputs, result: Simulation) =>
  input.scenarios.find((scenario) => scenario.name === result.scenario)!;
const scenarioLabel = (input: EconomyInputs, result: Simulation) =>
  scenarioFor(input, result).id.toUpperCase();

function sessionLabel(session: Session) {
  return `${dayNames(session.days)} ${time(session.at)}: ${number(session.minutes)} min ${session.mission ?? 'plain nap'}`;
}

function playerRow(player: PlayerPolicy) {
  return `| ${player.name} | ${player.sessions.map(sessionLabel).join('<br>')} | ${dayNames(player.visitDays)} ${time(player.visitAt)}; ${number(player.activeSeconds)} s active | ${player.feedsPerVisit} attempted / visit; ${player.sparWins.join('/')} wins Mon–Sun | ${player.targetLevel} |`;
}

function scenarioRow(input: EconomyInputs, scenario: Scenario) {
  const daytime =
    scenario.ceiling === null
      ? 'Uncapped'
      : `${number(scenario.ceiling)} in full, then ${number(scenario.excessRate * 100)}%`;
  const night =
    scenario.nightGift === null
      ? 'Per minute at the applicable window rate'
      : `${number(scenario.nightGift)} per qualifying night, outside daytime ceiling`;
  return `| ${scenario.name} | ${number(scenario.creditedMinutesPerRealMinute)} | ${number(input.rules.napPerMinute)} | ${number(scenario.restMultiplier)}× | ${number(scenario.focusMultiplier)}× | ${daytime} | ${night} | ${number(scenario.wellKeptGift)} |`;
}

/** The report and chart are generated together; neither reads the host date or clock. */
export function renderEconomyReport(input: EconomyInputs, simulations: Simulation[]): string {
  const today = input.scenarios.find((scenario) => scenario.id === 'today')!;
  const l2 = input.scenarios.find((scenario) => scenario.id === 'l2')!;
  const g10 = input.scenarios.find((scenario) => scenario.id === 'g10')!;
  const baseUrl = 'https://github.com/rempemat-eng/appify';
  const runtime = `${baseUrl}/blob/${input.source.main}`;
  const proposal = `${baseUrl}/blob/${input.source.proposal}/docs/vision/gameplay-regions.md`;
  const nightMinutes = 8 * 60;
  const nightToday =
    nightMinutes *
    today.creditedMinutesPerRealMinute *
    input.rules.napPerMinute *
    today.restMultiplier;
  const nightL2 =
    nightMinutes * l2.creditedMinutesPerRealMinute * input.rules.napPerMinute * l2.restMultiplier;
  const allHatPrices = input.hats.reduce((sum, hat) => sum + hat.cost, 0);
  const g10Results = simulations.filter((result) => scenarioFor(input, result).id === 'g10');
  const summaries = simulations.map(
    (result) =>
      `| ${scenarioLabel(input, result)} | ${result.player} | ${number(total(result.earned))} | ${number(total(result.spent))} | ${number(result.balance)} | ${result.level} | ${result.boughtHats.length} | ${result.freeHats.length} | ${result.allHatsDay ?? 'Not reached'} |`,
  );
  const flows = simulations.map(
    (result) =>
      `| ${scenarioLabel(input, result)} / ${result.player} | ${number(result.earned.naps)} | ${number(result.earned.outings)} | ${number(result.earned.nights)} | ${number(result.earned.spars)} | ${number(result.earned.wellKept)} | ${number(result.spent.feeding)} | ${number(result.spent.levels)} | ${number(result.spent.hats)} |`,
  );
  const wallets = simulations.map(
    (result) =>
      `| ${scenarioLabel(input, result)} / ${result.player} | ${weeklyWallets(input, result).map(number).join(' | ')} |`,
  );
  const activity = simulations.map(
    (result) =>
      `| ${scenarioLabel(input, result)} / ${result.player} | ${result.completedOutings} | ${result.gatedOutings} | ${result.earlyOutings} | ${result.feeds} | ${number(result.cards)} | ${[...result.boughtHats, ...result.freeHats].join(', ') || 'None'} |`,
  );

  return `# Dream Dust economy simulation (C33)

Generated by \`npm run sim:economy\` from [the typed inputs](../../scripts/economy-inputs.ts). This is a deterministic solo ledger over ${input.weeks} weeks (${input.weeks * input.daysPerWeek} fixed civil days), not a change to the game. Dream Dust is the requested reporting name for the existing \`grass\` balance; the runtime still calls it GRASS.

An actual eight-hour explicit nap pays **${number(nightToday)} today**, **${number(nightL2)} under L2**, or **${number(g10.nightGift ?? 0)} under G10**. Today's clock awards one displayed simulated minute per real second. All ${input.hats.length} current hats together cost ${number(allHatPrices)}. Comparing an eight-hour night with a compressed eight-minute demo would conceal this clock difference.

## Sources and scope

- Runtime and approved L2 snapshot: [main \`${input.source.main}\`](${baseUrl}/commit/${input.source.main}). Current prices, missions, spending and timing: [lib/game.ts](${runtime}/lib/game.ts); spar cap and play budget: [lib/offline-rules.ts](${runtime}/lib/offline-rules.ts); free card cadence: [lib/cards.ts](${runtime}/lib/cards.ts). L2 specifies Rest and Focus multipliers and a conditional well-kept gift in [living-world-plan.md](${runtime}/docs/vision/living-world-plan.md).
- Proposal snapshot: [PR #143, \`${input.source.proposal}\`](${proposal}), especially G10 and section 6.3. It remains a proposal. This simulation uses the existing three outings and current prices; it does not adopt G3's new regional outings, outfits, comforts, ways or other proposed sinks.
- Schedule and spending are explicit assumptions, not measured player behavior. Changing [economy-inputs.ts](../../scripts/economy-inputs.ts) and rerunning the command regenerates this report and its SVG without a seed, host clock or network.

## Inputs

All profiles begin with ${number(input.initial.dust)} Dust, level ${input.initial.level}, mood ${input.initial.mood}, and no hats. A week starts on Monday; session durations below are **real minutes in every scenario**. Outings stop earning at their completion deadline even when the scheduled return is later; they do not pay passive nap Dust as well. Only explicit rests count, rather than every hour the app is closed.

| Player | Repeating rest and outing schedule | Shopping / play visit | Feeding and spars | Target level |
| --- | --- | --- | --- | --- |
${input.players.map(playerRow).join('\n')}

Protected rhythm: ${input.rhythm.enabled ? 'enabled' : 'disabled'}. Rest: ${dayNames(input.rhythm.rest.days)}, ${time(input.rhythm.rest.start)}–${time(input.rhythm.rest.end)} (${input.rhythm.rest.enabled ? 'enabled' : 'disabled'}). Focus: ${dayNames(input.rhythm.focus.days)}, ${time(input.rhythm.focus.start)}–${time(input.rhythm.focus.end)} (${input.rhythm.focus.enabled ? 'enabled' : 'disabled'}). A window crossing midnight belongs to the weekday on which it starts. These are fixed civil-day arithmetic, with no host timezone or DST transition.

| Scenario | Credited min / real min | Plain nap Dust / credited min | Rest | Focus | Daytime payment | Qualifying night | Well-kept gift / eligible visit |
| --- | --- | --- | --- | --- | --- | --- | --- |
${input.scenarios.map((scenario) => scenarioRow(input, scenario)).join('\n')}

G10 nights need at least ${number(input.rules.nightMinimumMinutes)} real minutes and must start in the Rest window, or ${time(input.rhythm.fallbackNightStart)}–${time(input.rhythm.fallbackNightEnd)} with rhythm disabled. They grant at most ${input.rules.nightGiftLimitPerDay} gift per wake day; their minutes still grant cards. Its daytime ceiling combines naps and outings, pays ${number(g10.ceiling ?? 0)} in full plus ${number(g10.excessRate * 100)}% of the excess, and excludes the ${number(g10.nightGift ?? 0)} night gift and spars. **A ceiling is a taper, not a hard daily maximum.**

L2 and G10's approved daily well-kept gift has no agreed amount or health threshold. It is set to ${number(l2.wellKeptGift)} / ${number(g10.wellKeptGift)} respectively in these inputs; eligible days are assumed to be visit days. No invented medicine, repair or decor spend is added. Existing feeding costs ${number(input.rules.feedCost)}, restores ${number(input.rules.feedMood)} mood up to ${number(input.rules.maxMood)}, and only succeeds below full mood with an affordable balance. Each visit applies the configured active seconds at one mood per ${number(input.rules.awakeSecondsPerMood)} seconds before feeding; rest restores one mood per credited minute. These are ledger assumptions about visit timing, not a device-usage simulation.

At each visit: receive configured spar winnings and any well-kept gift, attempt feeding, buy **at most one level** toward the target, then buy **at most one unowned hat**, all subject to affordability. The target level is shopping policy, not a level cap. Levels cost ${number(input.rules.levelCostFactor)} × current level. Hats cost ${input.hats.map((hat) => `${hat.id} ${number(hat.cost)}`).join(', ')}. Mountain gives the first unowned hat in input order deterministically; runtime chooses an unowned hat randomly. Once all are owned, Mountain adds ${number(input.rules.mountainHatBonus)} Dust. A gated outing becomes a plain nap of the offered duration, another stated player policy. Visits are short and separated by rests, so the play allowance is not exhausted.

Outing rewards ${input.rules.multiplyOutings ? 'are multiplied proportionally by time spent in each protected window' : 'use their fixed amount without a protected-window multiplier'}, then paid at completion against that day's taper. This is an interpretation of L2/G10 for comparison, since L2's implementation is pending. The whole fixed reward, including Mountain's all-hats bonus, follows that interpretation. Plain-nap accrual splits at minute boundaries and midnight. A qualifying G10 night replaces all per-minute pay, even outside the Rest window. Failed outings keep their credited minutes/cards and pay no completion reward.

## ${input.weeks}-week results

Earned is gross new currency, excluding the starting ${number(input.initial.dust)}. Spent is actual successful purchases. **Wallet = ${number(input.initial.dust)} + earned − spent**; net new saving is earned − spent. Hat columns count purchases versus free Mountain grants, not duplicates. “All hats” is the first simulation day owning the current catalogue.

| Scenario | Player | Earned | Spent | Ending wallet | Level | Bought hats | Free hats | All hats day |
| --- | --- | ---: | ---: | ---: | ---: | ---: | ---: | ---: |
${summaries.join('\n')}

Under G10 these exact schedules earn ${g10Results.map((result) => `${result.player.toLowerCase()} ${number(total(result.earned))}`).join(', ')} over the horizon. These are not exact reproductions of #143's monthly sketch: the committed player uses today's Mountain (including its all-hats bonus), not the proposed regional outing, and no unset well-kept gift is invented. The regular profile is an additional comparison. Eight weeks is ${input.weeks * input.daysPerWeek} days, not two calendar months. These figures compare stated assumptions; they do not demonstrate improved time away from a phone.

## Sources and sinks

Night amounts appear under “Naps” for Today and L2 because those scenarios pay per minute; G10's flat gift appears separately. All values below are Dust, after any taper.

| Scenario / player | Naps | Outings | Night gifts | Spars | Well-kept | Feeding | Levels | Hats |
| --- | ---: | ---: | ---: | ---: | ---: | ---: | ---: | ---: |
${flows.join('\n')}

| Scenario / player | Completed outings | Gated → nap | Early outings | Feeds | Card grants | Hats owned |
| --- | ---: | ---: | ---: | ---: | ---: | --- |
${activity.join('\n')}

Card grants count free rewards, not unique cards or final deck size. Existing cards have no Dust purchase price. This ledger counts one common grant per ${number(input.rules.cardEveryMinutes)} cumulative credited minutes, one card per completed outing, and the level-three grant when applicable. It does not model deck composition or turn-based combat. Configured spar wins are assumed outcomes; only the first ${input.rules.paidSparWinsPerDay} daily wins pay ${number(input.rules.sparReward)} each.

## Weekly ending wallets

![Three panels compare weekly ending Dream Dust wallets for light, regular and committed players. Each scenario has its own labelled vertical scale.](economy-sim.svg)

The panels share player colors and week positions. **Vertical scales differ by scenario** to keep each comparison readable; compare the labels, not the apparent slopes across panels.

| Scenario / player | ${Array.from({ length: input.weeks }, (_, week) => `W${week + 1}`).join(' | ')} |
| --- | ${Array.from({ length: input.weeks }, () => '---:').join(' | ')} |
${wallets.join('\n')}

## Limits and reproducibility

- Solo only: raids, defense awards, Together bonuses and multiplayer are excluded. Today's raid losses therefore do not appear; L2's safe-currency change is not implemented by this work.
- No game rules, save schema, prices, art or UI change. The simulator is not imported by the app. Decorative keepsakes and hut choices remain free; no regional catalogue proposals are activated.
- Events use fixed civil minutes with deterministic ordering. No random visitors, random hats, runtime timer jitter, host date, timezone or DST is sampled. Plain-rest earnings are accrued by civil day; outing rewards and flat night gifts settle on completion/wake day.
- This models the authored rest/visit policy, including deliberately limited purchases; it is not an optimization or a forecast. Mountain's deterministic hat selection can shift purchase timing from runtime's random selection. Unknown L2 care eligibility, medicine prices and health thresholds remain outside this experiment.
- Run \`npm run sim:economy\` to regenerate [this Markdown](economy-sim.md) and [the accessible SVG](economy-sim.svg). Run \`npm run check:economy-sim\` for fixtures covering the model and deterministic report output.
`;
}

/** Standalone, accessible SVG; each panel declares its independent wallet scale. */
export function renderEconomyChart(input: EconomyInputs, simulations: Simulation[]): string {
  const width = 960;
  const panelHeight = 290;
  const top = 75;
  const height = top + input.scenarios.length * panelHeight + 26;
  const left = 105;
  const right = width - 35;
  const colors = ['#176B58', '#315DA8', '#B14C32'];
  const plots = input.scenarios
    .map((scenario, index) => {
      const panelTop = top + index * panelHeight;
      const plotTop = panelTop + 48;
      const plotBottom = panelTop + 236;
      const rows = simulations.filter((result) => result.scenario === scenario.name);
      const largest = Math.max(
        input.initial.dust,
        ...rows.flatMap((result) => weeklyWallets(input, result)),
      );
      const magnitude = 10 ** Math.floor(Math.log10(Math.max(1, largest)));
      const maximum = Math.max(1, Math.ceil(largest / magnitude) * magnitude);
      const x = (week: number) => left + ((right - left) * week) / input.weeks;
      const y = (wallet: number) => plotBottom - ((plotBottom - plotTop) * wallet) / maximum;
      const ticks = Array.from({ length: 5 }, (_, tick) => {
        const value = (maximum * tick) / 4;
        const at = y(value);
        return `<line x1="${left}" y1="${at}" x2="${right}" y2="${at}" stroke="#DCE3E9"/><text x="${left - 12}" y="${at + 5}" text-anchor="end">${number(value)}</text>`;
      }).join('');
      const weeks = Array.from(
        { length: input.weeks + 1 },
        (_, week) =>
          `<text x="${x(week)}" y="${plotBottom + 23}" text-anchor="middle">${week}</text>`,
      ).join('');
      const lines = rows
        .map((result) => {
          const playerIndex = input.players.findIndex((player) => player.name === result.player);
          const color = colors[playerIndex % colors.length];
          const values = [input.initial.dust, ...weeklyWallets(input, result)];
          const points = values.map((wallet, week) => `${x(week)},${y(wallet)}`).join(' ');
          return `<g><title>${escapeXml(result.player)}: ${values.map((wallet, week) => `week ${week} ${number(wallet)} Dust`).join('; ')}</title><polyline points="${points}" fill="none" stroke="${color}" stroke-width="3"/>${values.map((wallet, week) => `<circle cx="${x(week)}" cy="${y(wallet)}" r="3.5" fill="${color}"/>`).join('')}</g>`;
        })
        .join('');
      return `<g role="group" aria-labelledby="panel-${index}"><title id="panel-${index}">${escapeXml(scenario.name)}, independent scale zero to ${number(maximum)} Dust</title><text x="${left}" y="${panelTop + 13}" class="panel-title">${escapeXml(scenario.name)}</text><text x="${right}" y="${panelTop + 13}" text-anchor="end">Wallet: 0–${number(maximum)} Dust</text>${ticks}<line x1="${left}" y1="${plotTop}" x2="${left}" y2="${plotBottom}" stroke="#596A78"/><line x1="${left}" y1="${plotBottom}" x2="${right}" y2="${plotBottom}" stroke="#596A78"/>${weeks}${lines}<text x="${(left + right) / 2}" y="${plotBottom + 46}" text-anchor="middle">Simulation week</text></g>`;
    })
    .join('\n');
  const legend = input.players
    .map(
      (player, index) =>
        `<g transform="translate(${left + index * 220},47)"><line x1="0" y1="0" x2="24" y2="0" stroke="${colors[index % colors.length]}" stroke-width="3"/><text x="32" y="5">${escapeXml(player.name)}</text></g>`,
    )
    .join('');
  return `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${width} ${height}" width="${width}" height="${height}" role="img" aria-labelledby="chart-title chart-desc">
<title id="chart-title">Dream Dust ending wallets over ${input.weeks} weeks</title>
<desc id="chart-desc">Three scenario panels with independent labelled vertical scales. ${input.players.map((player) => player.name).join(', ')} keep the same colors. Lines include starting wallets and each week's ending wallet; exact values are in the accompanying Markdown table.</desc>
<style>text{font:14px system-ui,sans-serif;fill:#263846}.title{font-size:22px;font-weight:700}.panel-title{font-size:17px;font-weight:700}</style>
<rect width="100%" height="100%" fill="#FFFFFF"/>
<text x="${left}" y="26" class="title">Dream Dust wallets · independent scale per scenario</text>
${legend}
${plots}
</svg>\n`;
}
