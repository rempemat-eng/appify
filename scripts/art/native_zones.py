"""Zones drawn by the kit at density 2, and the folk the 2x walker draws.

    python3 scripts/art/native_zones.py

For every plan in art/scenes/ that names a "zone", renders it with the kit (each in its own
process, scripts/art/native/zone.py) and writes:
    lib/zone-native.ts          per zone: each object's native box and sprite, the flow box
    lib/zone-native-assets.ts   the pictures (ground, one per kind, flow)
    lib/folk-sprites.ts         Bramble and the Mossling's frame sheets (scripts/art/native/chars.py)
    assets/characters/folk/     those sheets
The game shows a native zone where the art density is 2 (`?density=2` on the web); its walk,
stands and ports are the 1x zone's own (lib/zone-maps.ts). Registered in check:art-repro.
"""
import json
import os
import re
import subprocess
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(os.path.dirname(HERE))
sys.path.insert(0, ROOT)


def camel(s: str) -> str:
    return ''.join(p[:1].upper() + p[1:] for p in re.split(r'[_\-/]', s) if p)


def main() -> int:
    zones = []
    sdir = os.path.join(ROOT, 'art', 'scenes')
    for n in sorted(os.listdir(sdir)):
        if n.endswith('.json') and json.load(open(os.path.join(sdir, n))).get('zone'):
            r = subprocess.run([sys.executable, '-m', 'scripts.art.native.zone', '--zone', n[:-5]], cwd=ROOT,
                               check=True, capture_output=True, text=True)
            zones.append(json.loads(r.stdout.strip().split('\n')[-1]))
            print('ok native zone', n[:-5])
    # the folk at 2x, from the perfected design (a fresh process: one density each)
    r = subprocess.run([sys.executable, '-c', (
        'import json, sys; sys.path.insert(0, %r)\n'
        'from scripts.art.native import export\n'
        'print(json.dumps(export.characters(%r, 2.0)))') % (ROOT, os.path.join(ROOT, 'assets', 'characters', 'folk'))],
        cwd=ROOT, check=True, capture_output=True, text=True)
    folk = json.loads(r.stdout.strip().split('\n')[-1])

    lines = ['// Generated by scripts/art/native_zones.py. Do not edit by hand.', "import type { ZoneId } from './zone-maps';", '',
             '/** A zone drawn by the kit at art density 2 (scripts/art/native/zone.py), shown where the',
             ' *  game draws at density 2. Its walk, stands and ports are the 1x zone\'s own (zone-maps.ts);',
             ' *  `objects` gives each object id its native sprite and box in zone pixels, its foot where',
             ' *  the 1x object\'s foot is, so the drawing order is unchanged; `flow` is the moving',
             ' *  water\'s box with its frames packed `cols` wide. */',
             'export type NativeZone = {',
             '  density: number;',
             '  objects: Record<string, readonly [string, number, number, number, number]>;',
             '  flow: readonly [number, number, number, number] | null;',
             '  flowCols: number;',
             '};',
             'export const zoneNative: Partial<Record<ZoneId, NativeZone>> = {']
    for z in zones:
        lines.append(f"  {z['zone']}: {{")
        lines.append(f"    density: {z['density']:g},")
        lines.append('    objects: {')
        for (oid, kind, x, y, w, h) in z['objects']:
            lines.append(f"      '{oid}': ['{kind}', {x:g}, {y:g}, {w:g}, {h:g}],")
        lines.append('    },')
        f = z['flow']
        lines.append(f"    flow: {('[' + ', '.join('%g' % v for v in f['rect']) + ']') if f else 'null'},")
        lines.append(f"    flowCols: {f['cols'] if f else 1},")
        lines.append('  },')
    lines.append('};')
    open(os.path.join(ROOT, 'lib', 'zone-native.ts'), 'w').write('\n'.join(lines) + '\n')

    a = ['// Generated by scripts/art/native_zones.py. Do not edit by hand.', "import type { ImageSourcePropType } from 'react-native';",
         "import type { ZoneId } from './zone-maps';"]
    body = []
    for z in zones:
        zc = camel(z['zone'])
        a.append(f"import native{zc}Ground from '@/assets/zones/{z['zone']}/2x/ground.png';")
        if z['flow']:
            a.append(f"import native{zc}Flow from '@/assets/zones/{z['zone']}/2x/flow.png';")
        for k in z['kinds']:
            a.append(f"import native{zc}{camel(k)} from '@/assets/zones/{z['zone']}/2x/{k}.png';")
    a += ['', '/** The pictures of the zones drawn at density 2 (zone-native.ts). */',
          'export const zoneNativeArt: Partial<',
          '  Record<ZoneId, { ground: ImageSourcePropType; flow: ImageSourcePropType | null; sprites: Record<string, ImageSourcePropType> }>',
          '> = {']
    for z in zones:
        zc = camel(z['zone'])
        body.append(f"  {z['zone']}: {{")
        body.append(f"    ground: native{zc}Ground,")
        body.append(f"    flow: {('native' + zc + 'Flow') if z['flow'] else 'null'},")
        body.append('    sprites: {')
        for k in z['kinds']:
            body.append(f"      {k}: native{zc}{camel(k)},")
        body.append('    },')
        body.append('  },')
    open(os.path.join(ROOT, 'lib', 'zone-native-assets.ts'), 'w').write('\n'.join(a + body + ['};']) + '\n')

    f = ['// Generated by scripts/art/native_zones.py from the kit (scripts/art/native/chars.py): do not edit.',
         "import type { ImageSourcePropType } from 'react-native';"]
    for name in sorted(folk):
        f.append(f"import folk{camel(name)} from '@/assets/characters/folk/{name}.png';")
    f += ['', '/** A folk or familiar in the perfected 2x design: one sheet, a row per facing and action',
          ' *  (rows), a column per frame; frame and foot in world px; ms per frame from the rig. */',
          'export type FolkSheet = {', '  src: ImageSourcePropType;', '  frame: readonly [number, number];',
          '  foot: readonly [number, number];', '  rows: readonly string[];',
          '  timing: Record<string, { frames: number; ms: readonly number[] }>;', '};',
          'export const folkSheets: Record<string, FolkSheet> = {']
    for name in sorted(folk):
        m = folk[name]
        timing = ', '.join(f"{a_}: {{ frames: {t['frames']}, ms: [{', '.join(str(v) for v in t['ms'])}] }}" for a_, t in m['timing'].items())
        f += [f'  {name}: {{', f'    src: folk{camel(name)},', f"    frame: [{m['frame'][0]:g}, {m['frame'][1]:g}],",
              f"    foot: [{m['foot'][0]:g}, {m['foot'][1]:g}],",
              f"    rows: [{', '.join(repr(r) for r in m['rows'])}],", f'    timing: {{ {timing} }},', '  },']
    f.append('};')
    open(os.path.join(ROOT, 'lib', 'folk-sprites.ts'), 'w').write('\n'.join(f) + '\n')
    return 0


if __name__ == '__main__':
    sys.exit(main())
