"""The coast kit's tileset, drawn pixel by pixel as data (no texture is computed).

The way Sea of Stars and Eastward build a sea cliff: a hand-drawn set of pieces laid by an
autotiler along each tier's organic outline. `coast_kit.py` holds the autotiler; this file
holds only the pictures. Every string is one row of pixels, west to east; every character
is a pixel:

    0 1 2 3 4 5   the piece's rock ramp at that tone (5 lit, 0 deepest shade); the column
                  or band picks its ramp (the cliff's rock: bleached sandstone, ashlar,
                  stone or basalt) when it is laid
    A B C D E F   the same tones on the ramp's warm sibling (one stone of the column)
    P Q R S T U   the same tones on the ramp's cool sibling
    K             the rock's edge tone: the joint between stones, a recess, an outline
    L M           grey-green lichen (grass_cool 2, 3)    O   orange sea lichen (clay_warm 4)
    g h i j k l   sea turf (grass), tones 0 to 5         G   the turf's edge tone
    a b c d e f   sand, tones 0 to 5 (the marram dune's lip, the feet on a beach)
    s t           thrift cushions in flower (berry 3, 4)  u   sea campion (snow 5)
    v w           pebbles on the feet (stone 2, 4)
    x y           weed and wrack (leaf_cool 1, 2)
    -  =          the rock under an overhang, one or two tones down (its shadow)
    .             nothing: what lies there already shows

What each set is for:
- COLUMNS: a sea cliff's face is a row of rock columns 10 to 24 px wide (the east px of
  each is the joint to the next), each a stack of rounded stones (Sea of Stars' pillow
  rock): three crowns (flush, set two rows down under a shaded recess, or standing back
  six rows), four bodies and two feet a width. The autotiler stacks a crown, bodies in
  hashed order and a foot to any face height, so no column repeats and no run of the face
  does. Wide columns are two stacks side by side whose joints never line up.
- LIPS: what hangs over a face from the top above it, 8 px a tile, four variants a kind:
  sea turf with thrift, a marram dune's sand lip, bare rock coping with lichen. Row 0 is
  the top's last row but one, row 2 the face's first row.
- BANDS and BAND_CAPS: the soft grid's side bands (5 px): a tier's west end lit, its east
  end in the two darkest tones; a cap where the lip turns the outer corner.
- FEET: the ground at the foot of a face on land, 8 px a tile: sand, shingle, the rock
  platform and turf. Where a face stands in the sea the surf draws its foot (coast_kit).
- HANGS: thrift and sea campion hanging over a face from a turf lip.

The columns were blocked out with a sketching aid that lays rounded stones, then finished
by hand (lichen, chips, the split columns); everything else here is drawn by hand.
"""

