"""The mountain kit's tileset, drawn pixel by pixel as data (no texture is computed).

The way top-down games build cliffs (Sea of Stars, Eastward, CrossCode): a hand-drawn set
of pieces laid by an autotiler along each tier's outline. `mountain_kit.py` holds the
autotiler; this file holds only the pictures. Every string is one row of pixels, west to
east; every character is a pixel:

    0 1 2 3 4 5   the piece's rock ramp at that tone (5 lit, 0 deepest shade); the column
                  or band picks its ramp (stone, ashlar or stone_warm) when it is laid
    A B C D E F   the same tones on the ramp's warm sibling (one stone of the column)
    P Q R S T U   the same tones on the ramp's cool sibling
    K             the rock's edge tone: a fissure between columns, a recess, an outline
    V W           a damp stain (slate_cool 1, 2)
    L M           lichen crusts (grass_cool 2, 3)
    a b c d e f   snow, tones 0 to 5          g h i j k l   grass (grass_cool), 0 to 5
    m n o p q r   moss and leaves (leaf), 0 to 5          G   the grass's edge tone
    ^ ~           the ledge's cover (snow or grass by height): lit, body
    - =           the rock under an overhang, one or two tones down (its shadow)
    .             nothing: what lies there already shows

Pieces that are not rock use their own key (the shore and the seracs, below).

What each set is for:
- COLUMNS: a face is a row of rock columns 6 to 32 px wide (the east px of each is the
  fissure to the next). Each width has three crowns (the column's top under the rim:
  flush, rounded two rows down, or standing back six rows with the recess above it in
  shade), five bodies (stones in a loose bond: one with its east fissure closed so two
  columns run together, one with a ledgelet carrying the cover) and two feet. The
  autotiler stacks a crown, bodies in hashed order and a foot to any face height (16, 32,
  48, 64), so no column repeats and no run of the face does.
- LIPS: what hangs over a face from the top above it, 8 px a tile, four variants a kind:
  a snow cornice, a turf lip with roots, a bare rock coping, a mossy coping. Row 0 is the
  top's last row but one, row 2 the face's first row.
- BANDS and BAND_CAPS: the soft grid's side bands (5 px): a tier's west end lit, its east
  end in the two darkest tones; a cap where the lip turns the corner (the outer corner).
- FEET: the ground at the foot of a face, 8 px a tile: the contact row, fallen stones lit
  on their upper left, grass or snow between them.
- SNOW_EDGE: where lying snow ends to the south: the lit lip, the snow's scalloped face,
  the ground under it in its shade.
- HANGS: grass and fern hanging over a face from a turf lip.
- SHORE: the tarn's banks (key below).
- SERACS: blocks of glacier ice for the icefall (key below).
"""

